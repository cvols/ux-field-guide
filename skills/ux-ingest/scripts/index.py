#!/usr/bin/env python3
"""Validate rules/ and sources/, then regenerate INDEX.md. Exits 1 on any error."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATEGORIES = [
    "layout", "hierarchy", "navigation", "forms", "feedback",
    "content", "choice", "motion", "accessibility", "onboarding",
]
CONFIDENCE = ["established", "single-source", "disputed"]
REQUIRED = ["title", "summary", "category", "principle", "confidence", "sources"]


def frontmatter(path):
    text = path.read_text()
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        return None
    fields = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        fields[key.strip()] = value
    return fields


def main():
    errors = []
    source_ids = {p.stem for p in (ROOT / "sources").glob("*.md")}
    rules = []
    for path in sorted((ROOT / "rules").glob("*.md")):
        name = path.relative_to(ROOT)
        fields = frontmatter(path)
        if fields is None:
            errors.append(f"{name}: no frontmatter")
            continue
        missing = [k for k in REQUIRED if not fields.get(k)]
        if missing:
            errors.append(f"{name}: missing {', '.join(missing)}")
            continue
        if fields["category"] not in CATEGORIES:
            errors.append(f"{name}: category must be one of {', '.join(CATEGORIES)}")
        if fields["confidence"] not in CONFIDENCE:
            errors.append(f"{name}: confidence must be one of {', '.join(CONFIDENCE)}")
        if not isinstance(fields["sources"], list):
            errors.append(f"{name}: sources must be a [list]")
            continue
        for source in fields["sources"]:
            if source not in source_ids:
                errors.append(f"{name}: unknown source {source} (no sources/{source}.md)")
        rules.append((path.stem, fields))

    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    lines = [
        "# Index",
        "",
        "Generated by `skills/ux-ingest/scripts/index.py`. Do not edit by hand.",
        "",
        f"{len(rules)} rules from {len(source_ids)} sources.",
    ]
    for category in CATEGORIES:
        in_category = sorted((r for r in rules if r[1]["category"] == category), key=lambda r: r[1]["title"])
        if not in_category:
            continue
        lines += ["", f"## {category}", ""]
        for slug, f in in_category:
            lines.append(f"- [{f['title']}](rules/{slug}.md): {f['summary']} *({f['principle']}, {f['confidence']})*")
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"INDEX.md: {len(rules)} rules")


if __name__ == "__main__":
    main()
